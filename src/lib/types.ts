// Shared by the app and by the Node asset scripts (keep it free of browser/Node-only imports).

export type Tier = 'high' | 'medium' | 'low'
export const TIERS = ['high', 'medium', 'low'] as const satisfies readonly Tier[]

export type Range = [min: number, max: number]

/** Texel classification: values are measured on the base-color texture (sRGB, 0–1; hue in degrees). */
export interface TexelSelector {
  lum?: Range
  sat?: Range
  hue?: Range
  /** Blue channel of the metallic-roughness texture. */
  metal?: Range
  /** Green channel of the metallic-roughness texture. */
  rough?: Range
}

/**
 * Which triangles belong to a customizable part. Criteria are combined with AND; parts are resolved in
 * order and a triangle belongs to the first part that claims it.
 */
export interface PartSelector {
  /** Source material names from the original .glb. */
  materials?: string[]
  texel?: TexelSelector
  /** Height of the triangle centroid, in meters above the floor (after normalization). */
  y?: Range
}

export interface ColorOption {
  id: string
  label: string
  /** sRGB hex. Omitted for `original`, which keeps the color of the source model. */
  color?: string
  metalness?: number
  roughness?: number
}

interface PartBase {
  id: string
  label: string
  select: PartSelector
  /** PBR overrides baked into the part material (removes its metallic-roughness texture). */
  metalness?: number
  roughness?: number
}

/** Plain colored surfaces (fabric, leather, plastic, paint): recolored at runtime, texture detail kept. */
export interface ColorPart extends PartBase {
  type: 'color'
  /** How much of the original texture contrast is kept (0–1, default 1). */
  detail?: number
  options: ColorOption[]
}

/** Wood surfaces: switched between pre-baked finish textures. */
export interface WoodPart extends PartBase {
  type: 'wood'
  /** Label of the finish the model ships with. */
  original: string
  /** `original` and/or ids from `catalog.finishes.wood`. */
  options: string[]
}

/** Metal surfaces: switched between metal finishes (color + metalness + roughness). */
export interface MetalPart extends PartBase {
  type: 'metal'
  original: string
  /** `original` and/or ids from `catalog.finishes.metal`. */
  options: string[]
}

export type ProductPart = ColorPart | WoodPart | MetalPart
export type PartType = ProductPart['type']

export interface MaterialOverride {
  alphaMode?: 'OPAQUE' | 'MASK' | 'BLEND'
  alphaCutoff?: number
  metalness?: number
  roughness?: number
  doubleSided?: boolean
}

export interface ProductModel {
  /** File name inside `assets/`. */
  source: string
  /** Multiplier converting the source units to meters (e.g. 0.01 for centimeters). */
  unitScale?: number
  /** Fixes applied to source materials (by name) before anything else. */
  materials?: Record<string, MaterialOverride>
}

export interface Product {
  slug: string
  name: string
  category: string
  price: number
  summary: string
  description: string
  materials: string[]
  model: ProductModel
  parts: ProductPart[]
}

export interface WoodFinish {
  label: string
  /** sRGB hex colors the darkest / lightest grain is mapped to. */
  dark: string
  light: string
}

export interface MetalFinish {
  label: string
  color: string
  metalness: number
  roughness: number
}

export interface Catalog {
  currency: string
  categories: { id: string; label: string }[]
  finishes: { wood: Record<string, WoodFinish>; metal: Record<string, MetalFinish> }
  products: Product[]
}

/* ---------- Generated by `pnpm models` (src/generated/models.json) ---------- */

export interface ModelFile {
  /** Path relative to the assets base URL, including a `?v=` content hash. */
  path: string
  bytes: number
  triangles: number
}

export interface PartEntry {
  type: PartType
  /** CSS colors of the original look: one color, or [dark, light] for wood. */
  swatch: string[]
  triangles: number
  /** Wood finishes: finish id → tier → material name → texture path (relative, with `?v=`). */
  textures?: Record<string, Record<Tier, Record<string, string>>>
}

export interface ModelEntry {
  /** Bounding box in centimeters. */
  dimensions: { width: number; height: number; depth: number }
  files: Record<Tier, ModelFile>
  parts: Record<string, PartEntry>
}

export interface ModelManifest {
  version: 1
  tiers: Record<Tier, { maxTextureSize: number; textures: string; geometry: string }>
  models: Record<string, ModelEntry>
}

export interface SnapshotImage {
  path: string
  width: number
  height: number
  srcset: { path: string; width: number }[]
}

/** Generated by `pnpm snapshots` (src/generated/snapshots.json). */
export interface SnapshotManifest {
  version: 1
  /** Real-world height (m) covered by the shared catalog camera. */
  sceneHeight: number
  images: Record<
    string,
    {
      /** Catalog camera shared by all products (natural relative scale), square. */
      catalog: SnapshotImage
      /** Same framing as the interactive viewer (4:3), used as its poster while the 3D model loads. */
      detail: SnapshotImage
    }
  >
}

export type SnapshotFraming = keyof SnapshotManifest['images'][string]

/** Material extras written by the pipeline (exposed as `material.userData.mdr` by GLTFLoader). */
export interface MaterialTag {
  part: string
  type: PartType
  /** Runtime color = target color (linear) / scale. */
  scale: number
  /** Name of the source material the part material was derived from. */
  source: string
}
